/**
 * Create a two-column signature block.
 */
export function createSignatureBlock(
  leftTitle: string,
  rightTitle: string
): Table {
  const signColumn = (title: string) =>
    new TableCell({
      width: { size: 50, type: WidthType.PERCENTAGE },
      margins: {
        top: convertMillimetersToTwip(3),
        bottom: convertMillimetersToTwip(3),
        left: convertMillimetersToTwip(5),
        right: convertMillimetersToTwip(5),
      },
      children: [
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { after: 40 },
          children: [
            new TextRun({
              text: title,
              bold: true,
              size: FONT_SIZE_NORMAL,
              font: FONT_NAME,
            }),
          ],
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { after: 40 },
          children: [
            new TextRun({
              text: "(Ký, ghi rõ họ tên)",
              size: FONT_SIZE_SMALL,
              font: FONT_NAME,
              color: COLOR_GRAY,
              italics: true,
            }),
          ],
        }),
        // Blank space for signature
        new Paragraph({ spacing: { after: 600 }, children: [] }),
        new Paragraph({ spacing: { after: 600 }, children: [] }),
      ],
    });

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
    },
    rows: [
      new TableRow({
        children: [signColumn(leftTitle), signColumn(rightTitle)],
      }),
    ],
  });
}


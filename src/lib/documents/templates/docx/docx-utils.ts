/**
 * DOCX Document Utilities
 * ───────────────────────
 * Reusable building blocks for creating styled Word documents
 * using the `docx` npm package. No external template files.
 *
 * Phase 6A.5.
 */

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  Table,
  TableRow,
  TableCell,
  WidthType,
  AlignmentType,
  BorderStyle,
  HeadingLevel,
  ShadingType,
  convertMillimetersToTwip,
} from "docx";

// ═══════════════════════════════════════════════════════
// STYLE CONSTANTS
// ═══════════════════════════════════════════════════════

const FONT_NAME = "Calibri";
const FONT_SIZE_NORMAL = 22;   // half-points → 11pt
const FONT_SIZE_SMALL = 20;    // 10pt
const FONT_SIZE_HEADING = 26;  // 13pt
const FONT_SIZE_TITLE = 32;    // 16pt
const FONT_SIZE_SUBTITLE = 28; // 14pt

const COLOR_BRAND = "2D5F2D";  // GreenPeat dark green
const COLOR_DARK = "1A1A1A";
const COLOR_GRAY = "666666";
const COLOR_HEADER_BG = "2D5F2D";
const COLOR_HEADER_TEXT = "FFFFFF";

const CELL_MARGIN = {
  top: convertMillimetersToTwip(1),
  bottom: convertMillimetersToTwip(1),
  left: convertMillimetersToTwip(2),
  right: convertMillimetersToTwip(2),
};

const TABLE_BORDER = {
  style: BorderStyle.SINGLE,
  size: 1,
  color: "CCCCCC",
};

const TABLE_BORDERS = {
  top: TABLE_BORDER,
  bottom: TABLE_BORDER,
  left: TABLE_BORDER,
  right: TABLE_BORDER,
  insideHorizontal: TABLE_BORDER,
  insideVertical: TABLE_BORDER,
};

// ═══════════════════════════════════════════════════════
// DOCUMENT CREATION

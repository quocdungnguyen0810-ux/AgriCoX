/**
 * Create a new DOCX Document with default styling and metadata.
 *
 * @param sections  Array of section children (paragraphs, tables, etc.)
 */
export function createDocxDocument(
  sections: (Paragraph | Table)[]
): Document {
  return new Document({
    creator: "AgriCoX / GreenPeat",
    title: "Document",
    description: "Generated by AgriCoX Document System",
    styles: {
      default: {
        document: {
          run: {
            font: FONT_NAME,
            size: FONT_SIZE_NORMAL,
            color: COLOR_DARK,
          },
          paragraph: {
            spacing: { after: 120 },
          },
        },
      },
    },
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: convertMillimetersToTwip(20),
              bottom: convertMillimetersToTwip(20),
              left: convertMillimetersToTwip(25),
              right: convertMillimetersToTwip(20),
            },
          },
        },
        children: sections,
      },
    ],
  });
}


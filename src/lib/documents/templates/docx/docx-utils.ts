/**
 * Ensure a value is a safe non-empty string for DOCX rendering.
 */
export function safeDocxText(
  value: string | null | undefined,
  fallback: string = "—"
): string {
  if (value == null) return fallback;
  const trimmed = value.trim();
  return trimmed || fallback;
}


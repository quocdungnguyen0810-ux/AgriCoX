/**
 * Create a styled table with header row and data rows.
 *
 * @param headers   Array of header column labels.
 * @param rows      Array of data rows (each row is an array of cell values).
 * @param colWidths Optional column widths in percentage (must sum to ~100).
 */
export function createTable(
  headers: string[],
  rows: string[][],
  colWidths?: number[]
): Table {
  // Header row
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) =>
      new TableCell({
        width: colWidths
          ? { size: colWidths[i], type: WidthType.PERCENTAGE }
          : undefined,
        shading: {
          type: ShadingType.SOLID,
          color: COLOR_HEADER_BG,
          fill: COLOR_HEADER_BG,
        },
        margins: CELL_MARGIN,
        children: [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [
              new TextRun({
                text: h,
                bold: true,
                size: FONT_SIZE_SMALL,
                font: FONT_NAME,
                color: COLOR_HEADER_TEXT,
              }),
            ],
          }),
        ],
      })
    ),
  });

  // Data rows
  const dataRows = rows.map(
    (row) =>
      new TableRow({
        children: row.map(
          (cell, i) =>
            new TableCell({
              width: colWidths
                ? { size: colWidths[i], type: WidthType.PERCENTAGE }
                : undefined,
              margins: CELL_MARGIN,
              children: [
                new Paragraph({
                  children: [
                    new TextRun({
                      text: cell,
                      size: FONT_SIZE_SMALL,
                      font: FONT_NAME,
                    }),
                  ],
                }),
              ],
            })
        ),
      })
  );

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: TABLE_BORDERS,
    rows: [headerRow, ...dataRows],
  });
}

/**
 * Create a simple two-column row (no header) for totals display.
 */
export function createTotalsTable(
  rows: Array<{ label: string; value: string; bold?: boolean }>
): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
    },
    rows: rows.map(
      (r) =>
        new TableRow({
          children: [
            // Spacer (60%)
            new TableCell({
              width: { size: 60, type: WidthType.PERCENTAGE },
              children: [new Paragraph({ children: [] })],
            }),
            // Label (20%)
            new TableCell({
              width: { size: 20, type: WidthType.PERCENTAGE },
              margins: CELL_MARGIN,
              children: [
                new Paragraph({
                  alignment: AlignmentType.RIGHT,
                  children: [
                    new TextRun({
                      text: r.label,
                      bold: true,
                      size: r.bold ? FONT_SIZE_NORMAL : FONT_SIZE_SMALL,
                      font: FONT_NAME,
                      color: r.bold ? COLOR_BRAND : COLOR_DARK,
                    }),
                  ],
                }),
              ],
            }),
            // Value (20%)
            new TableCell({
              width: { size: 20, type: WidthType.PERCENTAGE },
              margins: CELL_MARGIN,
              children: [
                new Paragraph({
                  alignment: AlignmentType.RIGHT,
                  children: [
                    new TextRun({
                      text: r.value,
                      bold: r.bold,
                      size: r.bold ? FONT_SIZE_NORMAL : FONT_SIZE_SMALL,
                      font: FONT_NAME,
                      color: r.bold ? COLOR_BRAND : COLOR_DARK,
                    }),
                  ],
                }),
              ],
            }),
          ],
        })
    ),
  });
}


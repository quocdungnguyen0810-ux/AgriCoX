/**
 * Create a document title paragraph (large, bold, green, centered).
 */
export function createTitle(text: string): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 80 },
    children: [
      new TextRun({
        text,
        bold: true,
        size: FONT_SIZE_TITLE,
        font: FONT_NAME,
        color: COLOR_BRAND,
      }),
    ],
  });
}

/**
 * Create a subtitle paragraph (medium, bold, centered).
 */
export function createSubtitle(text: string): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 200 },
    children: [
      new TextRun({
        text,
        bold: true,
        size: FONT_SIZE_SUBTITLE,
        font: FONT_NAME,
        color: COLOR_GRAY,
      }),
    ],
  });
}

/**
 * Create a section heading (bold, green, left-aligned).
 */
export function createHeading(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 300, after: 120 },
    children: [
      new TextRun({
        text,
        bold: true,
        size: FONT_SIZE_HEADING,
        font: FONT_NAME,
        color: COLOR_BRAND,
      }),
    ],
  });
}

/**
 * Create a regular paragraph.
 */
export function createParagraph(text: string): Paragraph {
  return new Paragraph({
    children: [
      new TextRun({
        text,
        size: FONT_SIZE_NORMAL,
        font: FONT_NAME,
      }),
    ],
  });
}

/**
 * Create a metadata line: bold label + normal value.
 */
export function createMetadataParagraph(
  label: string,
  value: string
): Paragraph {
  return new Paragraph({
    spacing: { after: 60 },
    children: [
      new TextRun({
        text: label + " ",
        bold: true,
        size: FONT_SIZE_NORMAL,
        font: FONT_NAME,
      }),
      new TextRun({
        text: value,
        size: FONT_SIZE_NORMAL,
        font: FONT_NAME,
      }),
    ],
  });
}

/**
 * Create a spacer paragraph.
 */
export function createSpacer(): Paragraph {
  return new Paragraph({ spacing: { after: 200 }, children: [] });
}

